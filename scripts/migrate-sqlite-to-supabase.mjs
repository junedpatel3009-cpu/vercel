import "dotenv/config";
import Database from "better-sqlite3";
import pg from "pg";

const apply = process.argv.includes("--apply");
const sqlitePath = process.env.SQLITE_MIGRATION_SOURCE || "prisma/app.db";
const connectionString = process.env.DIRECT_URL || process.env.DATABASE_URL;

if (!connectionString) throw new Error("DIRECT_URL or DATABASE_URL must be configured.");

const sqlite = new Database(sqlitePath, { readonly: true });
const client = new pg.Client({ connectionString });

function quote(identifier) {
  return `"${identifier.replaceAll('"', '""')}"`;
}

function postgresType(column) {
  const type = (column.type || "").toUpperCase();
  if (column.name === "id" && column.pk)
    return "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
  if (/^is[A-Z]|Enabled$/.test(column.name) && /INT/.test(type)) return "BOOLEAN";
  if (/At$|^deadline$|^jobDate$|^dueDate$/.test(column.name)) return "TIMESTAMPTZ";
  if (/INT/.test(type)) return "INTEGER";
  if (/REAL|FLOA|DOUB/.test(type)) return "DOUBLE PRECISION";
  if (/BLOB/.test(type)) return "BYTEA";
  return "TEXT";
}

function convertValue(column, value) {
  if (value === null || value === undefined) return null;
  if (/^is[A-Z]|Enabled$/.test(column.name) && /INT/.test((column.type || "").toUpperCase()))
    return Boolean(value);
  return value;
}

const tableOrder = new Map([
  ["User", 0],
  ["ClientProfile", 1],
  ["ClientSavedLocation", 2],
  ["ClientHiringNeed", 2],
  ["ServiceCategory", 1],
  ["ClientJob", 2],
  ["ClientJobAttachment", 3],
  ["FavoriteJob", 3],
  ["ProjectRequest", 3],
  ["ProjectNegotiation", 4],
  ["ProjectTracking", 4],
  ["ProjectWorkUpload", 5],
  ["ProjectRevisionRequest", 5],
  ["ProjectMilestone", 5],
  ["ProjectCompletionRequest", 5],
  ["ProjectTransaction", 6],
  ["ProjectReview", 6],
  ["ApiToken", 2],
  ["BrowserSubscription", 2],
  ["StoredFile", 2],
  ["Wallet", 2],
  ["WalletTransaction", 3],
]);

const tables = sqlite
  .prepare(
    "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
  )
  .all()
  .sort(
    (left, right) =>
      (tableOrder.get(left.name) ?? 10) - (tableOrder.get(right.name) ?? 10) ||
      left.name.localeCompare(right.name),
  );

await client.connect();
try {
  for (const { name: table } of tables) {
    const columns = sqlite.prepare(`PRAGMA table_info(${quote(table)})`).all();
    if (!columns.length) continue;

    const columnDefinitions = columns.map(
      (column) => `${quote(column.name)} ${postgresType(column)}`,
    );
    const count = sqlite.prepare(`SELECT COUNT(*) AS count FROM ${quote(table)}`).get().count;
    console.log(`${apply ? "Migrating" : "Would migrate"} ${table}: ${count} rows`);
    if (!apply) continue;

    await client.query(
      `CREATE TABLE IF NOT EXISTS ${quote(table)} (${columnDefinitions.join(", ")})`,
    );
    for (const column of columns) {
      await client.query(
        `ALTER TABLE ${quote(table)} ADD COLUMN IF NOT EXISTS ${quote(column.name)} ${postgresType(column)}`,
      );
    }

    const rows = sqlite.prepare(`SELECT * FROM ${quote(table)}`).all();
    const names = columns.map((column) => column.name);
    const placeholders = names.map((_, index) => `$${index + 1}`).join(", ");
    const insert = `INSERT INTO ${quote(table)} (${names.map(quote).join(", ")}) VALUES (${placeholders}) ON CONFLICT DO NOTHING`;

    await client.query("BEGIN");
    try {
      for (const row of rows) {
        await client.query(
          insert,
          columns.map((column) => convertValue(column, row[column.name])),
        );
      }
      const idColumn = columns.find((column) => column.name === "id");
      if (idColumn) {
        await client.query(
          `SELECT setval(pg_get_serial_sequence($1, 'id'), COALESCE((SELECT MAX(id) FROM ${quote(table)}), 1), true)`,
          [quote(table)],
        );
      }
      await client.query("COMMIT");
    } catch (error) {
      await client.query("ROLLBACK");
      throw new Error(
        `Failed while migrating ${table}: ${error instanceof Error ? error.message : String(error)}`,
      );
    }
  }
} finally {
  sqlite.close();
  await client.end();
}
